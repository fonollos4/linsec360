import json
import os
import re
import shlex
import tempfile
from pathlib import Path


HASH_PATTERN = re.compile(r"\$2[aby]\$(?:1[0-6]|0[4-9])\$[./A-Za-z0-9]{53}\Z")
USERNAME_PATTERN = re.compile(r"[A-Za-z0-9_.-]{1,64}\Z")


def render_config(root, environment=None):
    root = Path(root)
    if environment is None:
        environment = {**_read_env_file(root / ".env"), **os.environ}
    required = (
        "WAZUH_ADMIN_PASSWORD",
        "WAZUH_ADMIN_PASSWORD_HASH",
        "WAZUH_DASHBOARD_PASSWORD",
        "WAZUH_DASHBOARD_PASSWORD_HASH",
        "WAZUH_API_USERNAME",
        "WAZUH_API_PASSWORD",
    )
    missing = [key for key in required if not environment.get(key)]
    if missing:
        raise ValueError(f"Missing required Wazuh settings: {', '.join(missing)}")
    for key in ("WAZUH_ADMIN_PASSWORD_HASH", "WAZUH_DASHBOARD_PASSWORD_HASH"):
        if not HASH_PATTERN.fullmatch(environment[key]):
            raise ValueError(f"{key} must be a bcrypt hash generated by Wazuh")
    if not USERNAME_PATTERN.fullmatch(environment["WAZUH_API_USERNAME"]):
        raise ValueError("WAZUH_API_USERNAME contains unsupported characters")

    wazuh_dir = root / "config" / "wazuh"
    generated_dir = wazuh_dir / "generated"
    generated_dir.mkdir(parents=True, mode=0o700, exist_ok=True)
    os.chmod(generated_dir, 0o700)

    outputs = {
        generated_dir / "internal_users.yml": (
            wazuh_dir / "indexer" / "internal_users.yml.template",
            {
                "__ADMIN_HASH__": json.dumps(environment["WAZUH_ADMIN_PASSWORD_HASH"]),
                "__DASHBOARD_HASH__": json.dumps(
                    environment["WAZUH_DASHBOARD_PASSWORD_HASH"]
                ),
            },
        ),
        generated_dir / "wazuh.yml": (
            wazuh_dir / "dashboard" / "wazuh.yml.template",
            {
                "__API_USERNAME__": json.dumps(environment["WAZUH_API_USERNAME"]),
                "__API_PASSWORD__": json.dumps(environment["WAZUH_API_PASSWORD"]),
            },
        ),
    }

    for destination, (template_path, replacements) in outputs.items():
        content = template_path.read_text(encoding="utf-8")
        for token, value in replacements.items():
            content = content.replace(token, value)
        _write_private_file(destination, content)


def _read_env_file(path):
    if path.is_symlink():
        raise ValueError(".env must not be a symbolic link")
    if not path.exists():
        return {}
    os.chmod(path, 0o600)
    values = {}
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        key, separator, raw_value = stripped.partition("=")
        if not separator or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            raise ValueError(f"Invalid .env entry on line {line_number}")
        try:
            parsed = shlex.split(raw_value, comments=True, posix=True)
        except ValueError as exc:
            raise ValueError(f"Invalid .env value on line {line_number}") from exc
        values[key] = " ".join(parsed)
    return values


def _write_private_file(path, content):
    descriptor, temporary_path = tempfile.mkstemp(
        prefix=f".{path.name}-",
        dir=path.parent,
    )
    try:
        os.fchmod(descriptor, 0o644)
        with os.fdopen(descriptor, "w", encoding="utf-8") as output:
            output.write(content)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary_path, path)
    except Exception:
        try:
            os.unlink(temporary_path)
        except FileNotFoundError:
            pass
        raise


if __name__ == "__main__":
    render_config(Path(__file__).resolve().parents[2])
    print("Generated private Wazuh runtime configuration.")
